# What are ‘sessions’
# In Django, sessions are a framework that allows you to store and retrieve user-specific data across multiple,
# otherwise stateless, HTTP requests. This enables a website to maintain the "state" of a visitor's interaction,
# such as remembering a logged-in user, tracking items in a shopping cart, or counting page visits.
# The session framework works by storing the actual data securely on the server side,
# while a unique session ID is stored as a cookie in the user's browser.
# First Request: When a user visits the site for the first time, Django's session middleware generates a unique, random session ID.
# Cookie Exchange: This ID is sent to the browser as a sessionid cookie.
# Subsequent Requests: On all future requests, the browser sends this cookie back to the server.
# Data Retrieval: Django uses the ID from the cookie to retrieve the corresponding session data from its storage backend (e.g., a database table called django_session).


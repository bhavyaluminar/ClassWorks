# A CSRF token (Cross-Site Request Forgery token) is a unique, secret, and unpredictable value generated by a web application
# to protect against CSRF attacks. It acts as a security measure , ensure that incoming requests are comes from user ratherthan attackers site

# In a CSRF attack, an attacker crafts a  web page that contains a hidden form or JavaScript code which sends a request to website
# where the user is currently logged in. Because the browser automatically includes the users session cookies with the request,
# website treats this request as genuine and performs the unintended action

# when uses csrf_token
# When the server sends a form to the client, it includes a unique CSRF token, often in a hidden form field or an HTTP header.
# The server also stores this token (or a hash of it) in the user's session data on the server side.
# Validation: When the user submits the form, the browser sends the token back to the server.
# The server-side application then compares the received token with the one stored in the user's session.


